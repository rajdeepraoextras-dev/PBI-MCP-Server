"""Generate the MCP tool reference pages for the docs site.

Imports each server, lists its registered tools exactly as an MCP client
would (``list_tools``) and renders one Markdown page per server:

    docs/tools/model.md     the pbi-model server
    docs/tools/report.md    the pbi-report server

Each tool gets its access hints (read-only / destructive / idempotent, read
across the mcp 1.x camelCase and 2.x snake_case spellings), a parameter table
(type, required, default) taken from the input schema, and its description.
Tools are grouped into areas by name; anything unrecognised lands in
"Other tools", so new tool modules never need a change here to be listed.

    python scripts/gen_tool_reference.py            # rewrite docs/tools/*.md
    python scripts/gen_tool_reference.py --check    # exit 1 if they are stale
    python scripts/gen_tool_reference.py --out DIR  # write somewhere else

The output is identical under mcp 1.x and 2.x. tests/test_docs_reference.py
fails when the committed pages are stale.
"""

from __future__ import annotations

import argparse
import asyncio
import importlib
import inspect
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DEFAULT_OUT = REPO / "docs" / "tools"

if str(REPO) not in sys.path:      # `core` and the servers import from the repo
    sys.path.insert(0, str(REPO))

BANNER = ("<!-- Generated by scripts/gen_tool_reference.py from the live "
          "servers. Do not edit by hand; run the script instead. -->")

# --- areas: first matching rule wins; patterns are full-matched against the
# tool name without its "pbi_" prefix ----------------------------------------

