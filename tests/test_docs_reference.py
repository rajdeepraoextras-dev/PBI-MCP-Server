def test_access_hints_are_read_across_mcp_spellings(gen):
    class Ann:
        pass

    class Tool:
        name = "pbi_x"
        description = "Does x."
        inputSchema = {"properties": {}, "required": []}

    camel, snake = Ann(), Ann()
    camel.readOnlyHint, camel.destructiveHint, camel.idempotentHint = False, True, False
    snake.read_only_hint, snake.destructive_hint, snake.idempotent_hint = True, False, True
    a, b = Tool(), Tool()
    a.annotations, b.annotations = camel, snake
    da, db = gen.describe_tool(a), gen.describe_tool(b)
    assert (da["read_only"], da["destructive"], da["idempotent"]) == (False, True, False)
    assert (db["read_only"], db["destructive"], db["idempotent"]) == (True, False, True)
    assert gen._access(da) == "**Write** · destructive"
    assert gen._access(db) == "**Read-only** · idempotent"

    class Bare(Tool):
        annotations = None
        input_schema = {"properties": {}}
        inputSchema = None

    assert gen.describe_tool(Bare())["read_only"] is False


def test_parameters_come_from_the_input_schema(gen):
    class Tool:
        name = "pbi_demo"
        description = "  Demo tool.\n    Second line."
        annotations = None
        inputSchema = {
            "properties": {
                "table": {"type": "string", "title": "Table"},
                "limit": {"anyOf": [{"type": "integer"}, {"type": "null"}],
                          "default": 20},
                "mode": {"type": "string", "default": "fast",
                         "description": "How | fast"},
                "flag": {"type": "boolean", "default": False},
            },
            "required": ["table"],
        }

    tool = gen.describe_tool(Tool())
    assert tool["description"] == "Demo tool.\nSecond line."
    assert [(p["name"], p["type"], p["required"], p["default"])
            for p in tool["params"]] == [
        ("table", "string", True, ""),
        ("limit", "integer", False, "20"),
        ("mode", "string", False, '"fast"'),
        ("flag", "boolean", False, "false"),
    ]
    md = gen.render_tool(tool)
    assert "| `table` | string | yes |  |" in md
    assert "| `limit` | integer | no | `20` |" in md
    assert "Description |" in md and "How \\| fast" in md   # pipes escaped in cells


def test_descriptions_are_identical_whatever_the_python_docstring_handling(gen):
    """<= 3.12 keeps docstring indentation, >= 3.13 strips it at compile time.

    The dry-run note core.tooling appends is unindented, so a naive
    inspect.cleandoc leaves the older interpreters' indentation in place and
    the committed reference would differ per Python version.
    """
    from core.tooling import DRY_RUN_DOC

    class Tool:
        name = "pbi_x"
        annotations = None
        inputSchema = {"properties": {}}

        def __init__(self, description):
            self.description = description

    py312 = "Does x.\n    Second line.\n    Third line." + DRY_RUN_DOC
    py313 = "Does x.\nSecond line.\nThird line." + DRY_RUN_DOC
    expected = "Does x.\nSecond line.\nThird line." + DRY_RUN_DOC
    assert gen.describe_tool(Tool(py312))["description"] == expected
    assert gen.describe_tool(Tool(py313))["description"] == expected
    # tools without the appended note (reads, own-dry-run writes) are unchanged
    assert gen.describe_tool(Tool("Does x.\n    More."))["description"] == "Does x.\nMore."
    assert gen.describe_tool(Tool(""))["description"] == ""


