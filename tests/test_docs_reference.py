def test_cookbook_and_pages_name_only_real_tools():
    """Every `pbi_*` mentioned in prose must be a registered tool."""
    import asyncio

    try:
        import model_server.server as model
        import report_server.server as report
    except ImportError as exc:
        pytest.skip(f"a server could not be imported: {exc}")
    known = set()
    for mod in (model, report):
        known |= {t.name for t in asyncio.run(mod.mcp.list_tools())}
    bad = {}
    for page in DOCS.glob("*.md"):
        text = page.read_text(encoding="utf-8")
        if page.name == "development.md":       # its code fences use example names
            text = re.sub(r"```.*?```", "", text, flags=re.S)
        names = set(re.findall(r"\bpbi_[a-z0-9_]+\b", text))
        # a trailing underscore is a wildcard like pbi_* or pbi_service_
        unknown = {n for n in names if n not in known and not n.endswith("_")}
        # the optional cloud server's tools are documented generically
        if page.name == "cloud.md":
            unknown = set()
        if unknown:
            bad[page.name] = sorted(unknown)
    assert not bad, bad
