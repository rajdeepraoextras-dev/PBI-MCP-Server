def _nav_files() -> list[str]:
    text = (REPO / "mkdocs.yml").read_text(encoding="utf-8")
    block = re.search(r"^nav:\n((?:[ \t]+.*\n|\n)+)", text, re.M)
    assert block, "mkdocs.yml has no nav"
    return re.findall(r"([\w./-]+\.md)\b", block.group(1))


def test_nav_lists_only_existing_pages_and_every_page_is_in_the_nav():
    listed = set(_nav_files())
    assert len(listed) >= 10
    for rel in listed:
        assert (DOCS / rel).is_file(), f"nav points at missing docs/{rel}"
    on_disk = {p.relative_to(DOCS).as_posix() for p in DOCS.rglob("*.md")}
    assert on_disk == listed, f"pages not in nav: {sorted(on_disk - listed)}"


def _slug(heading: str) -> str:
    """Python-Markdown's toc slugify, as mkdocs uses for heading anchors."""
    text = re.sub(r"[`*]", "", heading)
    text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    text = re.sub(r"[^\w\s-]", "", text).strip().lower()
    return re.sub(r"[-\s]+", "-", text)


def _anchors(path: Path) -> set[str]:
    out, seen = set(), {}
    in_fence = False
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("```"):
            in_fence = not in_fence
        m = None if in_fence else re.match(r"#{1,6}\s+(.*?)\s*#*\s*$", line)
        if not m:
            continue
        slug = _slug(m.group(1))
        n = seen.get(slug, 0)
        seen[slug] = n + 1
        out.add(slug if n == 0 else f"{slug}_{n}")
    return out


def test_internal_links_resolve():
    link = re.compile(r"\]\(([^)\s]+)\)")
    problems = []
    for page in DOCS.rglob("*.md"):
        text = page.read_text(encoding="utf-8")
        text = re.sub(r"```.*?```", "", text, flags=re.S)
        for target in link.findall(text):
            if re.match(r"[a-z][a-z0-9+.-]*:", target) or target.startswith("#"):
                if target.startswith("#") and target[1:] not in _anchors(page):
                    problems.append(f"{page.name}: unknown anchor {target}")
                continue
            path, _, anchor = target.partition("#")
            dest = (page.parent / path).resolve()
            if not dest.is_file():
                problems.append(f"{page.relative_to(DOCS)}: {target} -> missing file")
            elif anchor and anchor not in _anchors(dest):
                problems.append(f"{page.relative_to(DOCS)}: {target} -> unknown anchor")
    assert not problems, "\n".join(problems)


