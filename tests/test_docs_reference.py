"""The docs site: generated tool reference is current, and the pages hang together."""

from __future__ import annotations

import difflib
import importlib.util
import re
import unicodedata
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parent.parent
DOCS = REPO / "docs"
TOOLS_DIR = DOCS / "tools"
STEMS = ("model", "report")


def _load_generator():
    spec = importlib.util.spec_from_file_location(
        "gen_tool_reference", REPO / "scripts" / "gen_tool_reference.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


@pytest.fixture(scope="module")
def gen():
    return _load_generator()


def _lf(data: bytes) -> str:
    return data.decode("utf-8").replace("\r\n", "\n")


# --- the generated reference ------------------------------------------------------

def test_committed_tool_reference_is_up_to_date(gen, tmp_path):
    try:
        written = gen.write_all(tmp_path)
    except ImportError as exc:
        pytest.skip(f"a server could not be imported: {exc}")
    assert sorted(p.name for p in written) == [f"{s}.md" for s in STEMS]
    for path in written:
        committed = TOOLS_DIR / path.name
        assert committed.exists(), (
            f"docs/tools/{path.name} is missing. Run: "
            "python scripts/gen_tool_reference.py")
        fresh, current = _lf(path.read_bytes()), _lf(committed.read_bytes())
        if fresh != current:
            diff = "\n".join(list(difflib.unified_diff(
                current.splitlines(), fresh.splitlines(),
                "committed", "regenerated", lineterm=""))[:40])
            pytest.fail(f"docs/tools/{path.name} is stale. Run: "
                        f"python scripts/gen_tool_reference.py\n{diff}")


